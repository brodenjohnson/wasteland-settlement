import json
ev = lambda s: pg.evaluate(s)
def shot(n): pg.screenshot(path='out/%s.png' % n)
pg.wait_for_timeout(1500)
print('saves ready:', ev('__g.state.savesReady'), '| characters at start:', ev('__g.state.chars.length'))
shot('s_title0')
ev('__g.newCharacter()'); pg.wait_for_timeout(300)
print('creation open:', ev('!!__g.state.creating'))
for ch in 'Rowan Vale': pg.keyboard.press('Space' if ch == ' ' else ch)
pg.keyboard.press('Backspace'); pg.keyboard.press('e'); pg.wait_for_timeout(200)
ev('Object.assign(__g.state.creating.look, {skin: "#8a5a3a", hair: "#a8742e", style: "long", feature: "scar", jacket: "#4a5a7a", scarf: "#c0392b"})')
pg.wait_for_timeout(300); shot('s_create')
print('typed name:', ev('__g.state.creating.name'))
pg.keyboard.press('Enter'); pg.wait_for_timeout(1200)
print('in game:', ev('!__g.state.title'), '| name:', ev('__g.state.player.name'), '| charId set:', ev('!!__g.state.charId'))
ev('Object.assign(__g.state.qflags, {storyInit:true, sitesPlaced:true, spawnVar:true, "read:Folded Note":true}); __g.state.intro = null; __g.state.reading = null')
pg.wait_for_timeout(800); shot('s_ingame')
# save to slots
ev('__g.addItem("Wood", 33)')
ev('__g.doSave("2", true)'); pg.wait_for_timeout(1500)
print('metas after saving slot 2 + autosave:', ev('JSON.stringify(__g.state.metaAll.map(m=>[m.slot,m.day,m.level,m.bytes]))'))
ev('__g.addItem("Scrap", 50)'); ev('__g.doSave("2", true)'); pg.wait_for_timeout(1200)
print('overwritten slot 2 saved at:', ev('__g.state.metaAll.filter(m=>m.slot==="2").length'), 'file(s)')
# reload the page: Continue should be offered
pg.reload(); pg.wait_for_timeout(2500)
print('after reload: chars', ev('__g.state.chars.length'), '| title:', ev('__g.state.title'))
shot('s_title1')
last = ev('JSON.stringify((()=>{ const c = __g.state.chars[0]; const m = __g.state.metaAll.filter(x=>x.charId===c.id).sort((a,b)=>b.savedAt-a.savedAt)[0]; return [c.id, m.slot]; })())')
cid, slot = json.loads(last)
ev('__g.loadSlot("%s", "%s")' % (cid, slot)); pg.wait_for_timeout(2000)
print('continued: in game', ev('!__g.state.title'), '| name', ev('__g.state.player.name'), '| wood', ev('__g.countItem("Wood")'), 'scrap', ev('__g.countItem("Scrap")'), '| look', ev('__g.state.char.look.style'))
shot('s_loaded')
